"""
frontend/build.py - reproducible frontend "build" (no Node toolchain needed).

The frontend is plain HTML/CSS/JavaScript served as-is. This script
  1. regenerates assets/js/templates.js (an embedded copy of pages/*.html so the
     app also works from file:// and offline), and
  2. with --check, fails if templates.js is stale, if any page or script uses
     inline event handlers / inline <script> (blocked by the Content-Security-
     Policy), or if `node --check` reports a JavaScript syntax error (skipped
     with a note when Node.js is not installed).

  python frontend/build.py           # write templates.js
  python frontend/build.py --check   # verify (used by tests and the release gate)
"""
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PAGES = os.path.join(HERE, "pages")
TEMPLATES = os.path.join(HERE, "assets", "js", "templates.js")
INLINE_HANDLER = re.compile(r"<[a-zA-Z][^<>]*\son[a-z]+\s*=\s*[\"']", re.I)
INLINE_SCRIPT = re.compile(r"<script(?![^>]*\bsrc=)[^>]*>", re.I)


def render() -> str:
    parts = []
    for name in sorted(os.listdir(PAGES)):
        if name.endswith(".html"):
            with open(os.path.join(PAGES, name), encoding="utf-8-sig") as f:
                parts.append(f"  {json.dumps(name[:-5])}: {json.dumps(f.read(), ensure_ascii=False)}")
    return ("/* Auto-generated by frontend/build.py from pages/*.html - do not edit by hand. */\n"
            "window.EMBEDDED_TEMPLATES = {\n" + ",\n".join(parts) + "\n};\n")


def check() -> int:
    problems = []
    with open(TEMPLATES, encoding="utf-8") as f:
        if f.read() != render():
            problems.append("assets/js/templates.js is out of date: run `python frontend/build.py`")
    files = [os.path.join(PAGES, n) for n in os.listdir(PAGES) if n.endswith(".html")]
    files.append(os.path.join(HERE, "index.html"))
    js_dir = os.path.join(HERE, "assets", "js")
    scripts = [os.path.join(js_dir, n) for n in os.listdir(js_dir)
               if n.endswith(".js") and n not in ("chart.umd.min.js", "templates.js")]
    for path in files + scripts:
        with open(path, encoding="utf-8-sig") as f:
            text = f.read()
        if INLINE_HANDLER.search(text):
            problems.append(f"inline event handler in {os.path.relpath(path, HERE)} (blocked by CSP)")
        if path.endswith(".html") and INLINE_SCRIPT.search(text):
            problems.append(f"inline <script> in {os.path.relpath(path, HERE)} (blocked by CSP)")
    node = shutil.which("node")
    if node:
        for path in scripts + [TEMPLATES]:
            r = subprocess.run([node, "--check", path], capture_output=True, text=True)
            if r.returncode:
                problems.append(f"JavaScript syntax error in {os.path.relpath(path, HERE)}: {r.stderr.strip()[:300]}")
    else:
        print("note: Node.js not found; JavaScript syntax check skipped")
    for p in problems:
        print("FAIL:", p)
    print("frontend check:", "OK" if not problems else f"{len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(check())
    with open(TEMPLATES, "w", encoding="utf-8") as f:
        f.write(render())
    print(f"wrote {os.path.relpath(TEMPLATES, HERE)}")
